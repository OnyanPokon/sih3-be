<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;

class RollbackModulCommand extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'rollback:module {name} {--type= : The type of module to rollback (central or tenant)}';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Rollback (delete) all files generated by the make:modul command';

    /**
     * Execute the console command.
     */
    public function handle()
    {
        $name = $this->argument('name');
        $type = $this->option('type');

        if (!$type || !in_array($type, ['central', 'tenant'])) {
            $this->error('Please specify a valid type: --type=central or --type=tenant');
            return 1;
        }

        // Konfirmasi sebelum melakukan aksi penghapusan
        if (!$this->confirm("Are you sure you want to PERMANENTLY DELETE all files for module '{$name}' of type '{$type}'? This cannot be undone.")) {
            $this->info('Operation cancelled.');
            return 0;
        }

        $typeDirectory = ucfirst($type);

        // Daftar file yang akan dihapus
        $filesToDelete = [
            'Controller' => app_path("Http/Controllers/{$typeDirectory}/{$name}Controller.php"),
            'Service'    => app_path("Http/Services/{$typeDirectory}/{$name}Service.php"),
            'Resource'   => app_path("Http/Resources/{$typeDirectory}/{$name}Resource.php"),
            'Request'    => app_path("Http/Requests/{$typeDirectory}/{$name}Request.php"),
            'Model'      => app_path("Models/{$typeDirectory}/{$name}.php"),
        ];

        foreach ($filesToDelete as $fileType => $path) {
            if (File::exists($path)) {
                File::delete($path);
                $this->info("{$fileType} deleted: {$path}");
            } else {
                $this->warn("{$fileType} not found: {$path}");
            }
        }

        // Penanganan khusus untuk file migrasi
        $this->handleMigrationDeletion($name, $type);

        $this->info("Rollback for module '{$name}' of type '{$type}' completed.");
        return 0;
    }

    /**
     * Find, rollback, and delete the migration file for the module.
     *
     * @param string $name
     * @param string $type
     * @return void
     */
    protected function handleMigrationDeletion(string $name, string $type)
    {
        $tableName = Str::snake(Str::plural($name));
        $migrationNameFragment = "create_{$tableName}_table";

        // Tentukan direktori migrasi berdasarkan tipe
        $migrationPath = ($type === 'tenant')
            ? database_path('migrations/tenant')
            : database_path('migrations');

        if (!File::isDirectory($migrationPath)) {
            $this->warn("Migration directory not found: {$migrationPath}");
            return;
        }

        // Cari file migrasi yang sesuai
        $files = File::glob($migrationPath . "/*_{$migrationNameFragment}.php");

        if (empty($files)) {
            $this->warn("Migration file for table '{$tableName}' not found.");
            return;
        }

        // Asumsikan hanya ada satu file migrasi yang cocok
        $migrationFilePath = $files[0];
        $relativePath = str_replace(base_path() . '/', '', $migrationFilePath);


        try {
            // Coba rollback migrasi terlebih dahulu
            $this->info("Attempting to rollback migration: {$relativePath}");
            $this->call('migrate:rollback', [
                '--path' => $relativePath,
                '--force' => true, // Gunakan force untuk lingkungan produksi
            ]);

            // Hapus file migrasi setelah berhasil di-rollback
            File::delete($migrationFilePath);
            $this->info("Migration file deleted: {$migrationFilePath}");
        } catch (\Exception $e) {
            $this->error("Could not rollback or delete migration file: {$e->getMessage()}");
            $this->warn("You may need to manually rollback and delete the migration file: {$migrationFilePath}");
        }
    }
}
